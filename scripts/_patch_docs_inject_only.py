def main() -> int:
    for rel, old, new in SUBS:
        p = ROOT / rel
        t = p.read_text(encoding="utf-8")
        n = t.count(old)
        if n != 1:
            print(f"!! [{rel}] 命中 {n} 次(期望1) -> 中止: {old[:56]!r}")
            return 1
        p.write_text(t.replace(old, new, 1), encoding="utf-8")
