const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(path.join(__dirname, '..', 'webui', 'index.html'), 'utf8');
const start = html.indexOf('function renderAttrSpecRuns(');
const close = html.slice(start).search(/^}\r?$/m);
assert.ok(start >= 0 && close >= 0);
const elements = {attrSpecRuns: {dataset: {}}, attrSpecRunsHint: {}};
const ctx = vm.createContext({$: id => elements[id]});
vm.runInContext(html.slice(start, start + close + 1), ctx);
ctx.info = {mode: 'price_band', runs: 7, min_runs: 5, default_runs: 5, ratio: 5 / 7};
vm.runInContext('renderAttrSpecRuns(info)', ctx);
assert.equal(elements.attrSpecRuns.value, 7);
assert.equal(elements.attrSpecRuns.dataset.saved, '7');
assert.ok(elements.attrSpecRunsHint.innerHTML.includes('每价格段 7 轮'));
assert.ok(elements.attrSpecRunsHint.innerHTML.includes('段×轮'));
assert.ok(elements.attrSpecRunsHint.innerHTML.includes('自动 = <b>5</b>'));
ctx.info = {...ctx.info, mode: 'uniform', min_runs_overridden: true, min_runs: 7};
vm.runInContext('renderAttrSpecRuns(info)', ctx);
assert.ok(!elements.attrSpecRunsHint.innerHTML.includes('每价格段'));
assert.ok(elements.attrSpecRunsHint.innerHTML.includes('自定义 = <b>7</b>'));
assert.ok(!elements.attrSpecRunsHint.innerHTML.includes('候选属性'), '候选属性列表已移除, 文案不应再提');
process.stdout.write('Effective Step 16 tuning descriptions passed.\n');
